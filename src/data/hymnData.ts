// 즐겨찾기(애창 찬송가) 로컬 스토리지 키
export const HYMN_FAVORITES_STORAGE_KEY = 'superbible_hymn_favorites';
export const HYMN_RECENT_STORAGE_KEY = 'superbible_hymn_recents';

export function getHymnFavorites(): number[] {
  try {
    const raw = localStorage.getItem(HYMN_FAVORITES_STORAGE_KEY);
    if (raw) return JSON.parse(raw);
  } catch (e) {
    console.error(e);
  }
  // 기본 애창 찬송가 세트 (1, 28, 79, 88, 94, 288, 305, 370, 412, 435, 563)
  return [1, 28, 79, 88, 94, 288, 305, 370, 412, 435, 563];
}

export function toggleHymnFavorite(num: number): boolean {
  const current = getHymnFavorites();
  let updated: number[];
  let isFav = false;
  if (current.includes(num)) {
    updated = current.filter((n) => n !== num);
    isFav = false;
  } else {
    updated = [num, ...current];
    isFav = true;
  }
  localStorage.setItem(HYMN_FAVORITES_STORAGE_KEY, JSON.stringify(updated));
  return isFav;
}

export function getRecentHymns(): number[] {
  try {
    const raw = localStorage.getItem(HYMN_RECENT_STORAGE_KEY);
    if (raw) return JSON.parse(raw);
  } catch (e) {}
  return [288, 1, 305, 79];
}

export function addRecentHymn(num: number): void {
  const current = getRecentHymns().filter((n) => n !== num);
  const updated = [num, ...current].slice(0, 20);
  localStorage.setItem(HYMN_RECENT_STORAGE_KEY, JSON.stringify(updated));
}
