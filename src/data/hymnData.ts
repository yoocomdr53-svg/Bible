function getHymnCategory(num: number): string {
  if (num <= 70) return '예배/찬양';
  if (num <= 181) return '성자/예수';
  if (num <= 206) return '은혜와 구원';
  if (num <= 310) return '은혜와 구원';
  if (num <= 340) return '믿음과 확신';
  if (num <= 384) return '기도와 간구';
  if (num <= 426) return '기도와 간구';
  if (num <= 470) return '헌신과 봉사';
  if (num <= 518) return '평안과 위로';
  if (num <= 549) return '전도와 선교';
  return '절기/행사';
}

